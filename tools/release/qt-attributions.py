#!/usr/bin/env python3
"""FK-014 (U028): writes licenses/Qt-third-party.md — the third-party components inside the Qt modules the packages
ship, with their copyright notices and licence texts, from Qt's own attribution files (qt_attribution.json).

Qt's binaries carry these components (FreeType, HarfBuzz, PCRE2, libpng, zlib, double-conversion, …); a
distribution of the Qt libraries has to reproduce their notices next to Qt's LGPL text.
Run it again when the Qt version changes (QT_VERSION in .github/workflows/*.yml):

  tools/release/qt-attributions.py <qt-source-dir> > licenses/Qt-third-party.md

<qt-source-dir> holds the qtbase and qtdeclarative source trees of that Qt version (the release's
qt-everywhere-src archive, or the two module archives). Parts used only on Linux or in Qt's tests, and modules
the app does not ship (Qt SQL), are left out.
"""
import json
import re
import sys
from pathlib import Path

SKIP = ("/testlib/", "/testinternal/", "/3rdparty/android", "/3rdparty/gradle", "/3rdparty/wasm",
        "/3rdparty/xcb", "/src/dbus", "/3rdparty/sqlite", "/examples/")


def entries(root: Path):
    for module in ("qtbase", "qtdeclarative"):
        for f in sorted((root / module / "src").rglob("qt_attribution.json")):
            rel = "/" + f.relative_to(root).as_posix()
            if any(s in rel for s in SKIP):
                continue
            data = json.loads(f.read_text(encoding="utf-8"), strict=False)
            for e in data if isinstance(data, list) else [data]:
                yield module, f.parent, e


def licence_texts(root: Path, module: str, folder: Path, e: dict) -> list[tuple[str, str]]:
    files = e.get("LicenseFiles") or ([e["LicenseFile"]] if e.get("LicenseFile") else [])
    out = []
    for name in files:
        p = (folder / name).resolve()
        if p.is_file():
            out.append((p.name, p.read_text(encoding="utf-8", errors="replace").strip()))
    if out:
        return out
    for spdx in re.findall(r"[A-Za-z0-9.+-]+", e.get("LicenseId", "")):
        if spdx in ("AND", "OR", "WITH"):
            continue
        for m in (module, "qtbase"):
            p = root / m / "LICENSES" / f"{spdx}.txt"
            if p.is_file():
                out.append((p.name, p.read_text(encoding="utf-8", errors="replace").strip()))
                break
    return out


def main() -> int:
    root = Path(sys.argv[1]).resolve()
    conf = (root / "qtbase" / ".cmake.conf").read_text(encoding="utf-8")
    version = re.search(r'QT_REPO_MODULE_VERSION "([^"]+)"', conf).group(1)
    items = sorted(entries(root), key=lambda x: x[2].get("Name", "").lower())
    print("# Third-party components in Qt", version)
    print()
    print("Generated by `tools/release/qt-attributions.py` from Qt", version, "(qtbase, qtdeclarative) — do not edit by")
    print("hand. These components are part of the Qt libraries shipped with FrameKeeper (Qt itself: LGPL-3.0, see")
    print("`Qt-LGPL-3.0-only.txt` and `README.md` in this folder). Linux-only parts, Qt's tests and Qt SQL are not")
    print("shipped and not listed. Where a component offers a choice of licences, the first one listed applies to")
    print("FrameKeeper's packages.")
    print()
    for module, folder, e in items:
        print(f"## {e.get('Name', e.get('Id'))}")
        print()
        if e.get("Version"):
            print(f"- Version: {e['Version']}")
        print(f"- Used in Qt: {e.get('QtUsage', '').strip()}")
        print(f"- Licence: {e.get('License', '')} (`{e.get('LicenseId', '')}`)")
        if e.get("Homepage"):
            print(f"- Homepage: {e['Homepage']}")
        cr = e.get("Copyright")
        lines = cr if isinstance(cr, list) else ([l for l in str(cr).splitlines() if l.strip()] if cr else [])
        if lines:
            print("- Copyright:")
            for l in lines:
                print(f"  - {l.strip()}")
        for name, text in licence_texts(root, module, folder, e):
            print()
            print(f"<details><summary>{name}</summary>")
            print()
            print("```text")
            print(text.replace("```", "'''"))
            print("```")
            print()
            print("</details>")
        print()
    return 0


if __name__ == "__main__":
    sys.exit(main())
